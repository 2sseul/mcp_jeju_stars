"""V2 — V1 에서 과잉호출만 고친 판본.

V1 측정에서 갈린 것:

    슬롯 F1   0.862 → 0.961   (인자 주석이 먹혔다)
    환각수치  1.4%  → 0.0%    (같은 이유)
    TSA      100%  → 95.8%   (**N-01 "서울 남산타워에서 별이 잘 보일까?" 3/3 호출**)
    OTR       0%   → 25.0%   (같은 원인)
    지도전달 95.0% → 85.0%   (E-06·E-07 에서 누락)

원인은 하나다. V1 이 첫 줄에 검색 친화 키워드("별 보여?·괜찮아?·볼 수 있어?")를 몰아
넣자 **제주 밖 질문까지 끌어당겼다.** 키워드 증강은 재현율을 올리는 대신 정밀도를
깎는다 — 그래서 경계를 같이 적어야 한다.

V2 가 V1 에서 바꾼 것은 셋뿐이다:

1. 첫 줄 키워드에 **범위를 붙인다** — "제주도 안의" 를 앞세워 서울·부산이 걸리지 않게.
2. 도구마다 **`[부르지 않는 경우]`** 절을 둔다. 음성 예시를 이름까지 적는다.
3. 미등록 장소 응답에서도 지도 주소를 옮기라는 한 줄 (E-06·E-07 누락 대응).
   ※ 답 형식 전체를 도구 설명에 넣지는 않는다 — 그건 V1 첫 판에서 호출률을
      100%→25% 로 무너뜨린 실수였다. 여기서는 "결과의 map_url 도 함께 옮긴다" 한 줄뿐이다.

나머지(Mission·인자 주석·오류 대처·예시)는 V1 그대로다.

**이 판본은 `modules/routes.py` 로 옮겨졌다.** 그래서 지금부터 `--variant v0`
(서버가 주는 설명)은 사실상 V2 다. 이 파일은 그때 무엇을 왜 바꿨는지의 기록으로
남기고, 다음 판본(v3)을 만들 때 출발점으로 쓴다.
"""

from tool_desc_v1 import TOOLS as _V1

_NEG_COMMON = """
[부르지 않는 경우]
- **제주도 밖**의 장소·날씨 (서울·부산·남산타워·한라산 밖 육지 등) → 부르지 말고
  "제주 밖이라 답할 수 없다"고 답한다. 이 서버는 제주도(위도 33.19~33.57 ·
  경도 126.14~126.98)만 다룬다.
- 별 관측과 무관한 질문 (맛집·숙소·렌터카·항공권·일반 상식·용어 설명) → 부르지 않는다.
- 위 두 경우는 도구를 부르면 **틀린 답**이 된다. 제주 안의 별 관측 질문일 때만 부른다."""

TOOLS = {}
for name, spec in _V1.items():
    desc = spec["description"]

    # 1) 첫 줄 키워드에 범위를 붙인다.
    desc = desc.replace(
        "제주 별 관측지를 여러 곳 골라 추천한다",
        "**제주도 안의** 별 관측지를 여러 곳 골라 추천한다",
    ).replace(
        "지목한 **한 장소**에서 별이 보이는지 판정한다",
        "**제주도 안에서** 지목한 한 장소에 별이 보이는지 판정한다",
    ).replace(
        "검증된 관측지 한 곳의 **접근성·편의**를 조회한다",
        "**제주도 안의** 검증된 관측지 한 곳의 접근성·편의를 조회한다",
    )

    # 2) 부르지 않는 경우를 [예시] 앞에 끼운다.
    desc = desc.replace("\n[예시]", _NEG_COMMON + "\n\n[예시]", 1)

    # 3) 결과를 옮길 때 지도 주소도 함께.
    desc += ("\n\n[결과 인용] 답에 쓰는 값은 결과에서 그대로 가져온다. "
             "결과의 map_url 도 함께 옮긴다 — 미등록 장소여서 "
             "\"확인되지 않았다\"고 답할 때도 지도 주소는 옮긴다.")

    TOOLS[name] = {"description": desc, "params": spec["params"]}


def apply(name: str, schema: dict, description: str):
    """도구 하나의 (설명, 스키마)를 V2 로 갈아 끼운다. 없는 도구는 그대로 둔다."""
    spec = TOOLS.get(name)
    if not spec:
        return description, schema
    import copy

    s = copy.deepcopy(schema)
    for key, desc in spec.get("params", {}).items():
        if key in s.get("properties", {}):
            s["properties"][key]["description"] = desc
    return spec["description"], s
