def apply(name: str, schema: dict, description: str):
    """운영 설명(V2+정정본) 위에 에러 명세와 인자 3축 주석을 얹는다.

    운영 설명을 통째로 갈아 끼우지 않는 것은, 그래야 A/B 가 **이번에 얹은 것만**
    분리해 재기 때문이다. 없는 도구·없는 인자는 그대로 둔다.
    """
    err = _ERRORS.get(name)
    if err is None:
        return description, schema

    desc = description.rstrip()
    # 기존 산문 [오류 대처] 는 그대로 두고 표를 뒤에 붙인다 — 지우면 무엇이 이겼는지
    # 갈리지 않는다. 표가 뒤에 오므로 모델이 마지막에 읽는 것이 구조화된 쪽이다.
    desc = f"{desc}\n{err.rstrip()}"

    s = copy.deepcopy(schema)
    for key, extra in _P.items():
        prop = s.get("properties", {}).get(key)
        if prop is None:
            continue
        base = (prop.get("description") or "").rstrip()
        prop["description"] = f"{base} {extra}".strip()
    return desc, s
